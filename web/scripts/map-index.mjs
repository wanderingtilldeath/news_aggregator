// Builds the two files the map pages read from the maps in lib/data/maps/*.json (run it after adding or changing a map,
// and commit the output):
//   node scripts/map-index.mjs
//   lib/data/maps/index.json  a small summary of every map (title, kind, count, a preview) for the library page, so it
//                             does not load every map's items
//   lib/maps-registry.ts      the maps themselves, imported statically so each viewer page is built with its own data
// The order of the kinds is the one in lib/map-catalog.ts (lib/map-catalog.test.ts checks they match).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const KINDS = ["political", "physical", "rivers", "climate", "wildlife", "economy", "heritage", "history", "world-seas", "world-capitals", "world-land"];
const dir = new URL("../lib/data/maps/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "index.json").sort();

const maps = files.map((f) => JSON.parse(readFileSync(new URL(f, dir), "utf8")));
const round = (n) => Math.round(n * 100) / 100;
const index = maps
  .map((m) => {
    if (!KINDS.includes(m.category)) throw new Error(`${m.id}: unknown category ${m.category}`);
    const entry = { id: m.id, title: m.title, category: m.category, blurb: m.blurb, kind: m.kind, base: m.base, source: m.source, licence: m.licence, asOf: m.asOf };
    if (m.approx) entry.approx = true;
    if (m.color) entry.color = m.color;
    if (m.kind === "point") entry.dots = m.items.map((i) => [round(i.lon), round(i.lat)]);
    if (m.kind === "point") entry.count = m.items.length;
    if (m.kind === "region") {
      const colors = Object.fromEntries(m.types.map((t) => [t.id, t.color]));
      entry.shade = Object.fromEntries(Object.entries(m.regions).map(([state, type]) => [state, colors[type]]));
      entry.count = Object.keys(m.regions).length;
    }
    if (m.kind === "line") {
      entry.count = m.lines.length;
      entry.color = m.color;
      entry.paths = m.lines.map((l) => l.d);
    }
    if (m.kind === "states") entry.count = 36;
    return entry;
  })
  .sort((a, b) => KINDS.indexOf(a.category) - KINDS.indexOf(b.category) || a.title.localeCompare(b.title));
writeFileSync(new URL("index.json", dir), JSON.stringify(index));

const ident = (id) => "m_" + id.replace(/[^a-z0-9]/gi, "_");
const registry = `// Generated by scripts/map-index.mjs: do not edit. Every map of lib/data/maps, by id, for the viewer pages.
import type { MapLayer } from "@/lib/maps";
${maps.map((m) => `import ${ident(m.id)} from "@/lib/data/maps/${m.id}.json";`).join("\n")}

export const MAPS: Record<string, MapLayer> = {
${maps.map((m) => `  "${m.id}": ${ident(m.id)} as unknown as MapLayer,`).join("\n")}
};
`;
writeFileSync(new URL("../lib/maps-registry.ts", import.meta.url), registry);
console.log(`${maps.length} maps: ${index.map((e) => `${e.id}(${e.count})`).join(", ")}`);
